"""Embed a locally built React application in the standalone Linux installer.

Build frontend/ with the locked pnpm dependencies first. No Node runtime or
network access is needed on the caster. Running this tool is deterministic.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / 'gnss-caster-install-3.0.1.sh'
START = '# BEGIN GENERATED REACT UI\n'
END = '# END GENERATED REACT UI\n'


def build_block(dist):
    files = {}
    for path in sorted((dist / 'assets').rglob('*')):
        if path.is_file():
            name = path.relative_to(dist).as_posix()
            files[name] = path.read_text(encoding='utf-8')
    manifest = json.loads((dist / '.vite/manifest.json').read_text(encoding='utf-8'))
    entry = manifest['src/main.jsx']['file']
    if entry not in files:
        raise ValueError('Missing frontend entry point')
    hashes = {name: hashlib.sha256(value.encode()).hexdigest() for name, value in files.items()}
    files['manifest.json'] = json.dumps({'entry': entry, 'sha256': hashes}, sort_keys=True)
    encoded = base64.b64encode(gzip.compress(json.dumps(files, sort_keys=True).encode(), mtime=0)).decode()
    lines = '\n'.join(encoded[i:i+120] for i in range(0, len(encoded), 120))
    block = START + '''# Generated by tools/embed_frontend.py; edit frontend/src instead.
install_react_ui() {
    "$VENV/bin/python" - "$APP/web/static/ui" << 'PYTHON_REACT_ASSETS'
import base64
import gzip
import hashlib
import json
import os
from pathlib import Path
import sys

payload = """
''' + lines + '''
"""
files = json.loads(gzip.decompress(base64.b64decode(payload)))
root = Path(sys.argv[1]).resolve()
manifest = json.loads(files['manifest.json'])
# Validate every name and digest before writing anything.
for name, content in files.items():
    path = (root / name).resolve()
    if not path.is_relative_to(root) or path == root:
        raise SystemExit('Unsafe frontend asset path')
    if name != 'manifest.json' and hashlib.sha256(content.encode()).hexdigest() != manifest['sha256'][name]:
        raise SystemExit('Frontend asset checksum mismatch')
for name, content in files.items():
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.new')
    with temporary.open('w', encoding='utf-8', newline='\\n') as output:
        output.write(content)
    os.replace(temporary, path)
print('React web assets installed')
PYTHON_REACT_ASSETS
}
''' + END
    return block, entry


def main():
    source = INSTALLER.read_text(encoding='utf-8')
    block, entry = build_block(ROOT / 'frontend/dist')
    if START in source:
        before, rest = source.split(START, 1)
        _, after = rest.split(END, 1)
        source = before + block + after
    else:
        marker = 'repair_installed_template_from_installer() {'
        source = source.replace(marker, block + '\n' + marker, 1)
    base = (ROOT / 'frontend/templates/base.html').read_text(encoding='utf-8').replace('__ENTRY__', entry).rstrip()
    templates = ['base', 'dashboard', 'base_stations', 'station_detail', 'rovers', 'mountpoints', 'rtcm_settings', 'system_configuration', 'user_settings', 'logs', 'login', 'login_2fa', 'error', '404', '500', 'diagnostics', 'backups']
    for name in templates:
        content = base if name == 'base' else ("{% set error_page = true %}\n" if name in ('error', '404', '500') else '') + '{% include "base.html" %}'
        if name in ('404', '500'):
            content = "{% set error = 'Page not found' %}\n" + content if name == '404' else "{% set error = 'An unexpected server error occurred' %}\n" + content
        marker = f"cat > $APP/web/templates/{name}.html << 'EOF'\n"
        if marker in source:
            before, rest = source.split(marker, 1)
            _, after = rest.split('\nEOF\n', 1)
            source = before + marker + content + '\nEOF\n' + after
        else:
            anchor = "cat > $APP/web/templates/base.html << 'EOF'\n"
            source = source.replace(anchor, marker + content + '\nEOF\n\n' + anchor, 1)
    with INSTALLER.open('w', encoding='utf-8', newline='\n') as output:
        output.write(source)
    print(f'Embedded React UI: {entry}; installer size {INSTALLER.stat().st_size:,} bytes')


if __name__ == '__main__':
    main()
