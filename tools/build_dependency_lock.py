"""Refresh the Linux runtime lock from PyPI metadata; does not install packages.
Review the generated lock and metadata diff before releasing it.
"""
import concurrent.futures
import json
from pathlib import Path
import re
import urllib.request
from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.specifiers import SpecifierSet
from pip._vendor.packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / 'gnss-caster-install.sh'
TARGETS = [dict(python_version=f'3.{v}', python_full_version=f'3.{v}.0',
                os_name='posix', sys_platform='linux', platform_system='Linux',
                platform_machine=machine, platform_python_implementation='CPython',
                implementation_name='cpython', implementation_version=f'3.{v}.0', extra='')
           for v in range(11,15) for machine in ('aarch64','armv7l','x86_64')]

def fetch(name, version=None):
    url = 'https://pypi.org/pypi/' + name + ('/' + version if version else '') + '/json'
    with urllib.request.urlopen(url, timeout=30) as response:
        data = json.load(response)
    return data

def applies(requirement):
    return not requirement.marker or any(requirement.marker.evaluate(target) for target in TARGETS)

def main():
    source = SCRIPT.read_text(encoding='utf-8')
    start_marker = "cat > $BASE/requirements.txt << 'EOF'\n"
    start = source.index(start_marker) + len(start_marker)
    end = source.index('\nEOF',start)
    # Preserve original direct pins. Deliberate pin changes belong in code review.
    pins = {}
    for line in source[start:end].splitlines():
        match = re.match(r'^([A-Za-z0-9_.-]+)==([^ ;\\]+)',line)
        if match: pins[canonicalize_name(match[1])] = match[2]
    pins.update({'bleak':'3.0.2', 'typing-extensions':'4.16.0',
                 'pip':'26.2.1', 'setuptools':'84.0.0', 'wheel':'0.48.0',
                 'bcrypt':'4.3.0'})
    metadata = {}
    pending = set(pins)
    while pending:
        names = sorted(pending)
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            results = list(pool.map(lambda name: fetch(name,pins.get(name)),names))
        pending = set()
        for name,data in zip(names,results):
            version = data['info']['version']
            pins[name] = version
            metadata[name] = {'version':version, 'requires_python':data['info']['requires_python'],
                              'requires_dist':data['info']['requires_dist'] or [],
                              'files':[{'filename':f['filename'],'sha256':f['digests']['sha256'],
                                        'yanked':f['yanked']} for f in data['urls'] if not f['yanked']]}
            for raw in metadata[name]['requires_dist']:
                req = Requirement(raw)
                if applies(req) and canonicalize_name(req.name) not in metadata:
                    pending.add(canonicalize_name(req.name))
    for name,item in metadata.items():
        for target in TARGETS:
            assert SpecifierSet(item['requires_python'] or '').contains(target['python_full_version']), (name,target)
        for raw in item['requires_dist']:
            req = Requirement(raw)
            if applies(req):
                assert req.specifier.contains(pins[canonicalize_name(req.name)]), (name,raw)
        assert item['files'], name
    lines = ['# Reviewed Linux runtime lock: CPython 3.11-3.14.',
             '# Generated by tools/build_dependency_lock.py from PyPI release metadata.',
             '# All runtime dependencies and installer tools are pinned and hashed.',
             '# Source builds still depend on OS/compiler and isolated build dependencies.']
    for name,item in sorted(metadata.items()):
        hashes = sorted({f['sha256'] for f in item['files']})
        lines.append(name+'=='+item['version']+' \\')
        lines.extend('    --hash=sha256:'+h+(' \\' if i<len(hashes)-1 else '') for i,h in enumerate(hashes))
    source = source[:start]+'\n'.join(lines)+'\n'+source[end:]
    SCRIPT.write_text(source,encoding='utf-8',newline='\n')
    (ROOT/'tests/dependency_metadata.json').write_text(json.dumps(metadata,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    print('Locked',len(metadata),'packages; checked',len(TARGETS),'Linux target environments')
    for name,item in sorted(metadata.items()): print(name+'=='+item['version'])

if __name__ == '__main__': main()
